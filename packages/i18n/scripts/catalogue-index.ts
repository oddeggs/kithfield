/**
 * Builds `src/catalogues.generated.ts`: one import per `<feature>.en.ts` / `<feature>.vi.ts`
 * pair in `src`, merged into the `en` and `vi` catalogues. `generate-catalogues.ts` writes it;
 * a test compares it with the committed file.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export const generatedFileName = 'catalogues.generated.ts';

/** A feature's pair of catalogue files, as found on disk. */
export interface CatalogueFiles {
  /** The file stem: `seed-bed`. */
  readonly file: string;
  /** The key prefix and export stem: `seedBed`. */
  readonly name: string;
  /** Whether the Vietnamese file exports `<name>SameInBoth`. */
  readonly hasSameInBoth: boolean;
}

const catalogueFile = /\.(en|vi)\.ts$/;
const kebabStem = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

export function exportStem(file: string): string {
  return file.replace(/-([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
}

function hasExport(source: string, name: string): boolean {
  return new RegExp(`export const ${name}\\b`).test(source);
}

/** The feature catalogue pairs in a folder, sorted by file name; throws on a broken pair. */
export function findCatalogueFiles(dir: string): CatalogueFiles[] {
  const stems = { en: new Set<string>(), vi: new Set<string>() };
  for (const fileName of readdirSync(dir)) {
    if (fileName.endsWith('.test.ts')) continue;
    const match = catalogueFile.exec(fileName);
    if (match === null) continue;
    const language = match[1] === 'vi' ? 'vi' : 'en';
    const stem = fileName.slice(0, -'.en.ts'.length);
    if (!kebabStem.test(stem)) {
      throw new Error(`${fileName}: name catalogue files <feature>.${language}.ts in kebab-case`);
    }
    stems[language].add(stem);
  }
  for (const stem of stems.en) {
    if (!stems.vi.has(stem)) throw new Error(`${stem}.en.ts has no ${stem}.vi.ts`);
  }
  for (const stem of stems.vi) {
    if (!stems.en.has(stem)) throw new Error(`${stem}.vi.ts has no ${stem}.en.ts`);
  }
  return [...stems.en].sort().map((file) => {
    const name = exportStem(file);
    const enSource = readFileSync(join(dir, `${file}.en.ts`), 'utf8');
    const viSource = readFileSync(join(dir, `${file}.vi.ts`), 'utf8');
    if (!hasExport(enSource, `${name}En`)) {
      throw new Error(`${file}.en.ts must export const ${name}En`);
    }
    if (!hasExport(viSource, `${name}Vi`)) {
      throw new Error(`${file}.vi.ts must export const ${name}Vi`);
    }
    return { file, name, hasSameInBoth: hasExport(viSource, `${name}SameInBoth`) };
  });
}

function block(lines: readonly string[]): string {
  return lines.length === 0 ? '{}' : `{\n${lines.join('\n')}\n}`;
}

/** The source of the generated index for these features. */
export function catalogueIndexSource(features: readonly CatalogueFiles[]): string {
  const imports = features.flatMap(({ file, name, hasSameInBoth }) => [
    `import { ${name}En } from './${file}.en';`,
    hasSameInBoth
      ? `import { ${name}SameInBoth, ${name}Vi } from './${file}.vi';`
      : `import { ${name}Vi } from './${file}.vi';`,
  ]);
  const entries = features.map(
    ({ file, name, hasSameInBoth }) =>
      `  { name: '${name}', file: '${file}', en: ${name}En, vi: ${name}Vi, sameInBoth: ${
        hasSameInBoth ? `${name}SameInBoth` : '[]'
      } },`,
  );
  const featureList = entries.length === 0 ? '[]' : `[\n${entries.join('\n')}\n]`;
  return [
    '// Generated by `pnpm --filter @kithfield/i18n gen` from the <feature>.en.ts and',
    '// <feature>.vi.ts files in this folder. Do not edit; re-run the generator instead.',
    "import type { FeatureCatalogues } from './catalogue-types';",
    ...imports,
    '',
    '/** Every feature catalogue pair, in file-name order. */',
    `export const features: readonly FeatureCatalogues[] = ${featureList};`,
    '',
    '/** The source catalogue: every key, in English. */',
    `export const en = ${block(features.map(({ name }) => `  ...${name}En,`))};`,
    '',
    '/** Every key, in Vietnamese. */',
    `export const vi = ${block(features.map(({ name }) => `  ...${name}Vi,`))};`,
    '',
  ].join('\n');
}

export function sourceDir(): string {
  return join(import.meta.dirname, '..', 'src');
}
