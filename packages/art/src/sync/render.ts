/**
 * What the sync writes into `src/vendor/`, as a pure function of the design file's bytes.
 *
 * - `kithfield-art.generated.js`: the design's renderer, byte for byte. Browsers run this one.
 * - `kithfield-art-module.generated.js`: the same bytes inside a function that takes the host
 *   (`window`, `document`, `customElements`…) as locals instead of reading browser globals, so the
 *   renderer runs unchanged on Skia without touching the app's global scope. One line is added at
 *   the end of the renderer's closure: it hands the host the drawing functions behind `<kf-art>`
 *   (scenes, the cast, coats, markings and outfits), which the layered critter cache draws one by
 *   one. A name the design drops makes that line throw when the module is evaluated.
 * - `kithfield-art-module.generated.d.ts`: its types.
 */

export interface SyncedFile {
  name: string;
  bytes: Buffer;
}

/** The renderer's closure ends with this; the internals line goes just before it. */
export const CLOSURE_END = '\n})();\n';

/** The drawing functions and tables handed to the host, by their names in the design file. */
export const INTERNALS = [
  'S',
  'CR',
  'COATS',
  'ANCH',
  'SEASONS',
  'PL',
  'NAMES',
  'LINEUP',
  'ROOF',
  'FRUIT',
  'RARE',
  'ICONS',
  'sprites',
  'sprite',
  'critterSprite',
  'drawCritter',
  'drawMark',
  'drawOutfit',
  'local',
  'duckling',
  'snail',
  'moth',
  'bfly',
  'ladybird',
  'flame',
  'sparks',
  'glow',
  'blinkAt',
] as const;

/** The browser globals the renderer reads, supplied by the host instead. */
export const HOST_GLOBALS = [
  'window',
  'document',
  'customElements',
  'HTMLElement',
  'ResizeObserver',
  'IntersectionObserver',
  'performance',
  'requestAnimationFrame',
  'matchMedia',
  'getComputedStyle',
  'Path2D',
  'console',
] as const;

const HEADER = `// @generated by packages/art/scripts/sync.ts from design/kithfield-art.js. Do not edit.
/* eslint-disable */
`;

export function renderModule(source: string): string {
  if (!source.endsWith(CLOSURE_END)) {
    throw new Error('design/kithfield-art.js no longer ends with its closure: update the sync');
  }
  const body = source.slice(0, source.length - CLOSURE_END.length);
  // `U` is the renderer's px-per-unit; layers drawn outside its sprite helper set it as it does.
  const hook = `\nwindow.KF.internals = { ${INTERNALS.join(', ')}, setU: (u) => { const p = U; U = u; return p; } };`;
  return `${HEADER}export function evaluateArt(host) {
const { ${HOST_GLOBALS.join(', ')} } = host;
${body}${hook}${CLOSURE_END}return window.KF;
}
`;
}

const DTS = `// @generated by packages/art/scripts/sync.ts. Do not edit.
/** Evaluates the design's renderer against \`host\` and returns its \`window.KF\`. */
export declare function evaluateArt(host: Record<string, unknown>): unknown;
`;

export function renderFiles(design: Buffer): SyncedFile[] {
  return [
    { name: 'kithfield-art.generated.js', bytes: Buffer.from(design) },
    {
      name: 'kithfield-art-module.generated.js',
      bytes: Buffer.from(renderModule(design.toString('utf8'))),
    },
    { name: 'kithfield-art-module.generated.d.ts', bytes: Buffer.from(DTS) },
  ];
}
