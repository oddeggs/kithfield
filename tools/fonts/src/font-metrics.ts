import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { readLineMetrics, type LineMetrics } from './sfnt';
import { fontSources } from './sources';
import { fontsDir } from './verify';

/** The module `@kithfield/theme` reads each embedded font's own line height from. */
export const metricsModulePath = join(
  import.meta.dirname,
  '../../../packages/theme/src/font-metrics.generated.ts',
);

/**
 * A font's own line height in ems, as Core Text (and so `UIFont.lineHeight`) sets it: hhea
 * ascender − descender + line gap over unitsPerEm. Core Text ignores USE_TYPO_METRICS (a copy of
 * Patrick Hand with the bit set and a taller typo ascender keeps its hhea height); it falls back to
 * the OS/2 typo metrics only when hhea has no ascender or descender.
 */
export function naturalLineHeight(m: LineMetrics): number {
  const v = m.hhea.ascender === 0 && m.hhea.descender === 0 ? m.typo : m.hhea;
  return (v.ascender - v.descender + v.lineGap) / m.unitsPerEm;
}

/** The generated module's source for the fonts in `dir`. */
export function metricsModule(dir: string = fontsDir): string {
  const rows = [...fontSources]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((s) => {
      const metrics = readLineMetrics(new Uint8Array(readFileSync(join(dir, s.file))));
      return `  '${s.name}': ${naturalLineHeight(metrics)},`;
    });
  return [
    '// Generated by `pnpm --filter @kithfield/fonts metrics` from `@kithfield/theme/fonts/`. Do not edit.',
    '',
    "import type { FontName } from './fonts';",
    '',
    '/**',
    ' * Each embedded font’s own line height in ems: the height iOS gives one line of it (hhea',
    ' * ascender − descender + line gap over unitsPerEm, as Core Text reads them).',
    ' */',
    'export const FONT_LINE_HEIGHT: Readonly<Record<FontName, number>> = {',
    ...rows,
    '};',
    '',
  ].join('\n');
}
