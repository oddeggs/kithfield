/**
 * Finds, for each sticker pose, the loop length at 30 fps (1.5 to 3 s) whose next frame comes back
 * closest to the first, since the art's motion isn't periodic in a round number of seconds:
 *
 *   pnpm --filter @kithfield/art-tools loops [--write]
 *
 * With `--write` it writes `apps/mobile/src/features/stickers/model/loop-lengths.generated.ts`.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';

import { allPacks } from '../../../apps/mobile/src/features/stickers/model/catalogue';
import { renderLoop, stickerArt, stickerAttrs } from './render';

const { values } = parseArgs({ options: { write: { type: 'boolean', default: false } } });

const FPS = 30;
const MIN = 45;
const MAX = 90;
const DEFAULT = 60;
const SIZE = 128;

const poses = new Set<string>(['face', 'hug2', 'squad', 'stack']);
for (const pack of allPacks()) for (const s of pack.stickers) poses.add(s.pose);

/** Mean absolute difference per channel, 0–255. */
function difference(a: Uint8Array, b: Uint8Array): number {
  let sum = 0;
  for (let i = 0; i < a.length; i++) sum += Math.abs((a[i] ?? 0) - (b[i] ?? 0));
  return sum / a.length;
}

const { art } = await stickerArt();
const look = { kind: 'rabbit', outfit: 'scarf', ocolor: '#5e7f4a' };
const best: Record<string, number> = {};
const rows: string[] = [];
for (const pose of [...poses].sort()) {
  const cast = pose === 'hug2' || pose === 'squad' || pose === 'stack' ? 'hedgehog/////' : '';
  const attrs = { ...stickerAttrs(look, pose, '-'), ...(cast ? { cast } : {}) };
  const loop = renderLoop(art, attrs, SIZE, FPS, MAX + 1);
  const first = loop.frames[0]?.rgba ?? new Uint8Array();
  let pick = DEFAULT;
  let pickDiff = Infinity;
  for (let n = MIN; n <= MAX; n++) {
    const d = difference(first, loop.frames[n]?.rgba ?? first);
    if (d < pickDiff - 1e-9) {
      pick = n;
      pickDiff = d;
    }
  }
  const atDefault = difference(first, loop.frames[DEFAULT]?.rgba ?? first);
  // Keep two seconds unless another length closes the seam clearly better.
  const chosen = pickDiff < atDefault * 0.5 ? pick : DEFAULT;
  best[pose] = chosen;
  rows.push(
    `${pose.padEnd(10)} 2 s seam ${atDefault.toFixed(2).padStart(6)}  best ${String(pick).padStart(2)} frames ` +
      `seam ${pickDiff.toFixed(2).padStart(6)}  -> ${chosen}`,
  );
}
console.log(rows.join('\n'));

if (values.write) {
  const file = resolve(
    import.meta.dirname,
    '../../../apps/mobile/src/features/stickers/model/loop-lengths.generated.ts',
  );
  const body = Object.entries(best)
    .map(([pose, n]) => `  ${/^[a-z][a-zA-Z0-9]*$/.test(pose) ? pose : `'${pose}'`}: ${n},`)
    .join('\n');
  writeFileSync(
    file,
    `// Generated by \`pnpm --filter @kithfield/art-tools loops --write\`; do not edit.\n` +
      `// Frames at 30 fps in each sticker pose's loop: the length (1.5 to 3 s) whose next frame\n` +
      `// comes back closest to the first, or two seconds when no length closes the seam clearly.\n\n` +
      `export const LOOP_FRAMES: Readonly<Record<string, number>> = {\n${body}\n};\n`,
  );
  console.log(`wrote ${file}`);
}
